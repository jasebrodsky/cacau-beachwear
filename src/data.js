export function getProduct(id) {
  return products.find((p) => p.id === id)
}

export function getPrevNext(id) {
  const i = products.findIndex((p) => p.id === id)
  if (i < 0) return { prev: null, next: null }
  return {
    prev: products[(i - 1 + products.length) % products.length],
    next: products[(i + 1) % products.length],
  }
}

export function getRelated(id, count = 3) {
  const { prev, next } = getPrevNext(id)
  const rest = products.filter((p) => p.id !== id && p.id !== prev?.id && p.id !== next?.id)
  return [next, prev, rest[0]].filter(Boolean).slice(0, count)
}
